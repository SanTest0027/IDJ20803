-- 1. Create table for students
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_no TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    marks NUMERIC(5,2) DEFAULT 0 NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;

-- Drop old policies if they exist
DROP POLICY IF EXISTS "Allow anon read on students" ON public.students;
DROP POLICY IF EXISTS "Allow anon update on students" ON public.students;

-- Allow read access to all users
CREATE POLICY "Allow anon read on students" 
ON public.students FOR SELECT 
TO anon, authenticated 
USING (true);

-- Allow update access (for lecturer mark edits)
CREATE POLICY "Allow anon update on students" 
ON public.students FOR UPDATE 
TO anon, authenticated 
USING (true);

-- 3. Enable Realtime publication for students table
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND tablename = 'students'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.students;
  END IF;
END $$;

